#!/usr/bin/env bun
/**
 * Writes skills/<name>/references/commands.md: the --help text of every xr command, the same for each skill.
 * Run `bun run skills:refs` after a command or an option changes; a test fails on a stale file.
 */

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import type { Command } from "commander";
import { createProgram } from "../src/cli/index.ts";

const HELP_WIDTH = 80;

/** Each command with no subcommand, with its path, in the order of the program. */
export function leafCommands(
  command: Command,
  prefix = "",
): [string, Command][] {
  if (command.commands.length === 0) return [[prefix, command]];
  return command.commands.flatMap((child) =>
    leafCommands(child, prefix ? `${prefix} ${child.name()}` : child.name()),
  );
}

/** The xr program the reference is built from. */
export const PROGRAM = createProgram({
  write: () => {},
  help: () => {},
  select: () => {},
});
/** The root and every command with no subcommand: the commands of the reference. */
export const COMMANDS: [string, Command][] = [
  ["", PROGRAM],
  ...leafCommands(PROGRAM),
];
/** Each skill gets its own copy: `npx skills add --skill <name>` installs only that folder. */
export const SKILL_FOLDERS = ["xr", "xr-init", "xr-hooks"];

/** The commands as Markdown: a `## xr <path>` heading, then the help text in a code block. */
export function renderCommandsReference(
  commands: readonly [string, Command][],
): string {
  const sections = commands.map(([path, command]) => {
    command.configureHelp({ helpWidth: HELP_WIDTH });
    const heading = path ? `xr ${path}` : "xr";
    return `## ${heading}\n\n\`\`\`text\n${command.helpInformation().trimEnd()}\n\`\`\`\n`;
  });
  return `<!-- Generated by bun run skills:refs from the xr --help text. Do not edit. -->\n\n# xr commands\n\n${sections.join("\n")}`;
}

if (import.meta.main) {
  const root = new URL("../", import.meta.url);
  const text = renderCommandsReference(COMMANDS);
  for (const skill of SKILL_FOLDERS) {
    const dir = new URL(`skills/${skill}/references/`, root);
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    writeFileSync(new URL("commands.md", dir), text);
    console.log(`skills/${skill}/references/commands.md`);
  }
}
